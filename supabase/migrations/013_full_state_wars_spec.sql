-- Replace activity resolver: exactly 3 choices/day on Beginner Island and 4 on
-- normal states, deterministic offers shared by chat/Mini App, safer beginner
-- outcomes and the -10% contribution penalty after leaving the island.
create or replace function public.gw_complete_activity(
  p_player_id uuid,
  p_state_id uuid,
  p_activity_key text,
  p_option_key text
) returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  tpl public.activity_templates%rowtype;
  s public.states%rowtype;
  p public.players%rowtype;
  option_data jsonb;
  risk numeric:=0;
  success boolean:=true;
  rc integer:=0;
  ri integer:=0;
  rt integer:=0;
  rr integer:=0;
  rcon integer:=0;
  result_message text;
  run_id uuid;
  daily_limit integer:=4;
begin
  select * into p from public.players where id=p_player_id for update;
  if not found then raise exception 'Игрок не найден.'; end if;
  select * into s from public.states where id=p_state_id for update;
  if not found then raise exception 'Государство не найдено.'; end if;
  if not exists(select 1 from public.state_members where player_id=p_player_id and state_id=p_state_id) then raise exception 'Игрок не состоит в этом государстве.'; end if;

  daily_limit:=case when s.is_beginner_island then 3 else 4 end;
  if (select count(*) from public.player_activity_runs where player_id=p_player_id and completed_at>=date_trunc('day',now()))>=daily_limit then
    raise exception 'Все ежедневные активности на сегодня уже выполнены.';
  end if;
  if exists(select 1 from public.player_activity_runs where player_id=p_player_id and activity_key=p_activity_key and completed_at>=date_trunc('day',now())) then
    raise exception 'Эта активность уже выполнена сегодня.';
  end if;

  if not exists(
    select 1 from (
      select at.key
      from public.activity_templates at
      where at.active=true and (not s.is_beginner_island or at.beginner_allowed=true)
      order by md5(at.key||':'||p_player_id::text||':'||current_date::text)
      limit daily_limit
    ) offered where offered.key=p_activity_key
  ) then raise exception 'Эта активность не входит в сегодняшний набор.'; end if;

  select * into tpl from public.activity_templates where key=p_activity_key and active=true;
  if not found then raise exception 'Активность не найдена.'; end if;
  select value into option_data from jsonb_array_elements(tpl.options) where value->>'key'=p_option_key limit 1;
  if option_data is null then raise exception 'Вариант действия не найден.'; end if;

  risk:=greatest(0,least(0.8,coalesce((option_data->>'risk')::numeric,0)));
  if s.is_beginner_island then risk:=least(risk,0.08); end if;
  success:=random()>=risk;
  rc:=coalesce((option_data->>'credits')::integer,0);
  ri:=coalesce((option_data->>'influence')::integer,0);
  rt:=coalesce((option_data->>'tech')::integer,0);
  rr:=coalesce((option_data->>'reputation')::integer,0);
  rcon:=coalesce((option_data->>'contribution')::integer,0);

  if not success then
    rc:=floor(rc*0.25)::integer; ri:=floor(ri*0.25)::integer; rt:=floor(rt*0.25)::integer;
    rr:=least(rr,-2); rcon:=greatest(2,floor(rcon*0.4)::integer);
    result_message:=case when s.is_beginner_island then 'Учебная попытка вышла неидеально, но вы сохранили минимальную награду. Подсказка: выбирайте варианты с меньшим риском.' else 'План сработал не полностью. Часть награды потеряна из-за риска.' end;
  else
    result_message:=case when s.is_beginner_island then 'Тренировка прошла успешно. Получены опыт, репутация и вклад.' else 'Операция выполнена успешно.' end;
  end if;

  if p.contribution_penalty_until is not null and p.contribution_penalty_until>now() then rcon:=greatest(1,floor(rcon*0.90)::integer); end if;

  update public.states set credits=credits+greatest(0,rc),influence=influence+greatest(0,ri),tech=tech+greatest(0,rt),reputation=greatest(-1000,least(1000,reputation+rr)) where id=p_state_id;
  update public.state_members set contribution=greatest(0,contribution+rcon) where state_id=p_state_id and player_id=p_player_id;
  update public.players set xp=xp+greatest(2,rcon),personal_reputation=personal_reputation+rr where id=p_player_id;
  insert into public.contribution_events(player_id,state_id,source,amount,metadata) values(p_player_id,p_state_id,'activity',rcon,jsonb_build_object('activity',p_activity_key,'option',p_option_key,'success',success));
  insert into public.player_activity_runs(player_id,state_id,activity_key,option_key,result_text,reward_credits,reward_influence,reward_tech,reward_reputation,reward_contribution)
  values(p_player_id,p_state_id,p_activity_key,p_option_key,result_message,rc,ri,rt,rr,rcon) returning id into run_id;

  return jsonb_build_object('id',run_id,'success',success,'text',result_message,'credits',rc,'influence',ri,'tech',rt,'reputation',rr,'contribution',rcon,'penaltyActive',coalesce(p.contribution_penalty_until>now(),false));
end;
$$;
revoke all on function public.gw_complete_activity(uuid,uuid,text,text) from public,anon,authenticated;
grant execute on function public.gw_complete_activity(uuid,uuid,text,text) to service_role;

-- Leadership rule from the brief: combat/diplomacy support comes from president
-- or deputy; curator is allowed only because Beginner Island has no president.
create or replace function public.gw_add_battle_support(
  p_battle_id uuid,
  p_support_state_id uuid,
  p_player_id uuid,
  p_side text
) returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  b public.battles%rowtype;
  support_state public.states%rowtype;
  base_power integer;
  current_support integer:=0;
  cap_power integer;
  granted integer;
  target_state uuid;
  support_role text;
begin
  if p_side not in ('attacker','defender') then raise exception 'Некорректная сторона поддержки.'; end if;
  select * into b from public.battles where id=p_battle_id for update;
  if not found or b.status not in ('scheduled','active') then raise exception 'Битва уже недоступна для поддержки.'; end if;
  select sm.role into support_role from public.state_members sm where sm.state_id=p_support_state_id and sm.player_id=p_player_id;
  if support_role is null or support_role not in ('president','minister','deputy','curator') then raise exception 'Поддержку может отправить президент, заместитель или куратор.'; end if;
  if p_support_state_id in (b.attacker_state_id,b.defender_state_id) then raise exception 'Участник боя не считается союзной поддержкой.'; end if;
  select * into support_state from public.gw_refresh_state_strategy(p_support_state_id);
  if support_role='curator' and not support_state.is_beginner_island then raise exception 'Куратор действует только на Острове новичков.'; end if;
  if support_state.is_beginner_island and p_side='attacker' then raise exception 'Остров новичков может помогать только в обороне.'; end if;

  target_state:=case when p_side='attacker' then b.attacker_state_id else b.defender_state_id end;
  if not exists(
    select 1 from public.diplomacy_relations dr
    where ((dr.state_a_id=p_support_state_id and dr.state_b_id=target_state) or (dr.state_b_id=p_support_state_id and dr.state_a_id=target_state)) and dr.status='allied'
  ) then raise exception 'Поддерживать можно только союзника.'; end if;

  base_power:=case when p_side='attacker' then b.attacker_raw_power else b.defender_raw_power end;
  cap_power:=greatest(1,floor(base_power*0.35)::integer);
  select coalesce(sum(power_given),0)::integer into current_support from public.battle_supports where battle_id=p_battle_id and side=p_side;
  granted:=least(greatest(1,floor((case when p_side='attacker' then support_state.army_power else support_state.defense_power end)*0.15)::integer),greatest(0,cap_power-current_support));
  if granted<=0 then raise exception 'Лимит союзной поддержки для этой стороны уже достигнут.'; end if;

  insert into public.battle_supports(battle_id,state_id,side,support_type,power_given,contributed_by_player_id)
  values(p_battle_id,p_support_state_id,p_side,case when p_side='attacker' then 'attack' else 'defense' end,granted,p_player_id);
  insert into public.contribution_events(player_id,state_id,source,amount,metadata)
  values(p_player_id,p_support_state_id,'support',greatest(5,granted/20),jsonb_build_object('battleId',p_battle_id,'side',p_side,'training',support_state.is_beginner_island));
  update public.state_members set contribution=contribution+greatest(5,granted/20) where player_id=p_player_id and state_id=p_support_state_id;
  if support_state.is_beginner_island then
    update public.players set xp=xp+greatest(8,granted/15), personal_reputation=personal_reputation+2 where id=p_player_id;
    update public.states set reputation=least(1000,reputation+2) where id=p_support_state_id;
  end if;
  return jsonb_build_object('power',granted,'side',p_side,'cap',cap_power,'training',support_state.is_beginner_island,'xp',case when support_state.is_beginner_island then greatest(8,granted/15) else 0 end,'reputation',case when support_state.is_beginner_island then 2 else 0 end);
end;
$$;
revoke all on function public.gw_add_battle_support(uuid,uuid,uuid,text) from public,anon,authenticated;
grant execute on function public.gw_add_battle_support(uuid,uuid,uuid,text) to service_role;

-- ---------------------------------------------------------------------------
-- Draws: close battles are genuine draws instead of implicit defender wins.
-- ---------------------------------------------------------------------------
alter table public.battles add column if not exists is_draw boolean not null default false;

create or replace function public.gw_finalize_battle(
  p_battle_id uuid,
  p_attacker_score integer,
  p_defender_score integer
) returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  b public.battles%rowtype;
  winner_id uuid;
  attacker_won boolean:=false;
  battle_draw boolean:=false;
  v_resolved_at timestamptz:=now();
  attacker_rating integer;
  defender_rating integer;
  expected_attacker double precision;
  attacker_delta integer:=0;
  defender_delta integer:=0;
  loot bigint:=0;
  ruined_until timestamptz;
  defender_integrity integer:=100;
  new_integrity integer:=100;
  integrity_damage integer:=0;
  score_margin integer:=0;
  score_total numeric:=1;
  island_destroyed boolean:=false;
  rating_result numeric:=0;
begin
  select * into b from public.battles where id=p_battle_id for update;
  if not found then raise exception 'Битва не найдена.'; end if;
  if b.status in ('resolved','cancelled') then return jsonb_build_object('applied',false,'battle',to_jsonb(b),'isDraw',b.is_draw); end if;

  score_total:=greatest(1,greatest(0,p_attacker_score)+greatest(0,p_defender_score));
  battle_draw:=abs(p_attacker_score-p_defender_score)/score_total<0.05;
  attacker_won:=not battle_draw and p_attacker_score>p_defender_score;
  winner_id:=case when battle_draw then null when attacker_won then b.attacker_state_id else b.defender_state_id end;

  update public.battles set
    status='resolved',attacker_score=greatest(0,p_attacker_score),defender_score=greatest(0,p_defender_score),
    winner_state_id=winner_id,is_draw=battle_draw,resolved_at=v_resolved_at,last_tick_at=v_resolved_at
  where id=b.id returning * into b;

  if b.battle_kind='island' then
    if b.defender_state_id is null then raise exception 'У островной битвы нет защитника.'; end if;
    perform 1 from public.states where id in (b.attacker_state_id,b.defender_state_id) order by id for update;
    select rating into attacker_rating from public.states where id=b.attacker_state_id;
    select rating,island_integrity into defender_rating,defender_integrity from public.states where id=b.defender_state_id;
    new_integrity:=defender_integrity;

    expected_attacker:=1.0/(1.0+power(10.0,(defender_rating-attacker_rating)/400.0));
    rating_result:=case when battle_draw then 0.5 when attacker_won then 1.0 else 0.0 end;
    attacker_delta:=round(36.0*(rating_result-expected_attacker))::integer;
    if not battle_draw and attacker_delta=0 then attacker_delta:=case when attacker_won then 1 else -1 end; end if;
    defender_delta:=-attacker_delta;

    update public.states set
      rating=greatest(0,rating+attacker_delta),rating_peak=greatest(rating_peak,greatest(0,rating+attacker_delta)),
      island_wins=island_wins+case when not battle_draw and attacker_won then 1 else 0 end,
      island_losses=island_losses+case when not battle_draw and not attacker_won then 1 else 0 end,
      win_streak=case when battle_draw then 0 when attacker_won then win_streak+1 else 0 end,
      best_win_streak=greatest(best_win_streak,case when not battle_draw and attacker_won then win_streak+1 else 0 end),
      last_battle_at=v_resolved_at
    where id=b.attacker_state_id;

    update public.states set
      rating=greatest(0,rating+defender_delta),rating_peak=greatest(rating_peak,greatest(0,rating+defender_delta)),
      island_wins=island_wins+case when not battle_draw and not attacker_won then 1 else 0 end,
      island_losses=island_losses+case when not battle_draw and attacker_won then 1 else 0 end,
      win_streak=case when battle_draw then 0 when attacker_won then 0 else win_streak+1 end,
      best_win_streak=greatest(best_win_streak,case when not battle_draw and not attacker_won then win_streak+1 else 0 end),
      last_battle_at=v_resolved_at
    where id=b.defender_state_id;

    if attacker_won then
      score_margin:=greatest(0,p_attacker_score-p_defender_score);
      integrity_damage:=least(55,greatest(22,22+floor(score_margin/8.0)::integer));
      new_integrity:=greatest(0,defender_integrity-integrity_damage);
      update public.states set island_integrity=new_integrity where id=b.defender_state_id;
      if new_integrity<=0 then
        island_destroyed:=true;
        -- Resource capture is handled exclusively by gw_apply_battle_strategy_rewards
        -- so the design-brief loot cap can never be bypassed by legacy destruction loot.
        loot:=0;
        ruined_until:=now()+interval '2 hours';
        update public.states set island_integrity=0,destroyed_until=ruined_until,
          shield_until=greatest(coalesce(shield_until,now()),now()+interval '10 hours') where id=b.defender_state_id;
      end if;
    end if;

    return jsonb_build_object('applied',true,'battle',to_jsonb(b),'battleKind','island','isDraw',battle_draw,
      'attackerRatingDelta',attacker_delta,'defenderRatingDelta',defender_delta,'integrityDamage',integrity_damage,
      'defenderIntegrity',new_integrity,'islandDestroyed',island_destroyed,'lootCredits',loot,
      'destroyedStateId',case when island_destroyed then b.defender_state_id else null end,'destroyedUntil',ruined_until);
  end if;

  if b.war_id is not null then
    update public.wars set status='resolved',winner_state_id=winner_id,attacker_power=greatest(0,p_attacker_score),
      defender_power=greatest(0,p_defender_score),resolved_at=v_resolved_at where id=b.war_id;
  end if;
  if not battle_draw and attacker_won then
    update public.tiles set owner_state_id=b.attacker_state_id,defense=2,is_capital=false where id=b.tile_id;
    update public.states set rating=rating+35,rating_peak=greatest(rating_peak,rating+35),credits=credits+350 where id=b.attacker_state_id;
  elsif not battle_draw then
    update public.tiles set defense=least(8,defense+1) where id=b.tile_id;
    update public.states set rating=greatest(0,rating-8) where id=b.attacker_state_id;
  end if;
  return jsonb_build_object('applied',true,'battle',to_jsonb(b),'battleKind','territory','isDraw',battle_draw);
end;
$$;
revoke all on function public.gw_finalize_battle(uuid,integer,integer) from public,anon,authenticated;
grant execute on function public.gw_finalize_battle(uuid,integer,integer) to service_role;

create or replace function public.gw_apply_battle_strategy_rewards(p_battle_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  b public.battles%rowtype;
  a public.states%rowtype;
  d public.states%rowtype;
  attacker_won boolean;
  score_total numeric:=1;
  margin numeric:=0;
  win_loss numeric:=0.10;
  lose_loss numeric:=0.18;
  budget_pct numeric:=0.20;
  influence_pct numeric:=0.15;
  budget_cap bigint:=0;
  budget_take bigint:=0;
  influence_take bigint:=0;
  a_recovery bigint:=0;
  d_recovery bigint:=0;
begin
  select * into b from public.battles where id=p_battle_id for update;
  if not found then raise exception 'Битва не найдена.'; end if;
  if b.status<>'resolved' then raise exception 'Битва ещё не завершена.'; end if;
  if b.strategy_rewards_applied then return jsonb_build_object('applied',false,'stolenBudget',b.stolen_budget,'stolenInfluence',b.stolen_influence,'attackerLossPct',b.attacker_loss_pct,'defenderLossPct',b.defender_loss_pct,'isDraw',b.is_draw); end if;
  if b.defender_state_id is null then update public.battles set strategy_rewards_applied=true where id=b.id; return jsonb_build_object('applied',true); end if;

  perform 1 from public.states where id in (b.attacker_state_id,b.defender_state_id) order by id for update;
  select * into a from public.states where id=b.attacker_state_id;
  select * into d from public.states where id=b.defender_state_id;

  if b.is_draw or b.winner_state_id is null then
    a_recovery:=least(1500::bigint,floor(a.credits*0.04)::bigint);
    d_recovery:=least(1500::bigint,floor(d.credits*0.04)::bigint);
    update public.states set credits=greatest(0,credits-a_recovery),shield_until=greatest(coalesce(shield_until,now()),now()+interval '4 hours') where id=a.id;
    update public.states set credits=greatest(0,credits-d_recovery),shield_until=greatest(coalesce(shield_until,now()),now()+interval '4 hours') where id=d.id;
    update public.battles set attacker_loss_pct=0.12,defender_loss_pct=0.12,stolen_budget=0,stolen_influence=0,strategy_rewards_applied=true where id=b.id;
    return jsonb_build_object('applied',true,'isDraw',true,'stolenBudget',0,'stolenInfluence',0,'attackerLossPct',0.12,'defenderLossPct',0.12,'attackerRecoveryCost',a_recovery,'defenderRecoveryCost',d_recovery);
  end if;

  attacker_won:=b.winner_state_id=b.attacker_state_id;
  score_total:=greatest(1,b.attacker_score+b.defender_score);
  margin:=abs(b.attacker_score-b.defender_score)/score_total;
  win_loss:=least(0.18,greatest(0.05,0.08+margin*0.12));
  lose_loss:=least(0.25,greatest(0.15,0.16+margin*0.16));
  if b.battle_type='siege' then budget_pct:=0.12; influence_pct:=0.10;
  elsif b.battle_type='territory' then budget_pct:=0.08; influence_pct:=0.08; end if;

  if attacker_won then
    budget_cap:=least(5000::bigint,(1000+a.game_level*300)::bigint);
    budget_take:=least(floor(d.credits*budget_pct)::bigint,budget_cap);
    influence_take:=least(floor(d.influence*influence_pct)::bigint,greatest(50::bigint,budget_cap/10));
    update public.states set credits=greatest(0,credits-budget_take),influence=greatest(0,influence-influence_take),shield_until=greatest(coalesce(shield_until,now()),now()+interval '8 hours') where id=d.id;
    update public.states set credits=credits+budget_take,influence=influence+influence_take where id=a.id;
    update public.battles set attacker_loss_pct=round(win_loss,4),defender_loss_pct=round(lose_loss,4),stolen_budget=budget_take,stolen_influence=influence_take,strategy_rewards_applied=true where id=b.id;
  else
    update public.states set shield_until=greatest(coalesce(shield_until,now()),now()+interval '6 hours') where id=a.id;
    update public.battles set attacker_loss_pct=round(lose_loss,4),defender_loss_pct=round(win_loss,4),stolen_budget=0,stolen_influence=0,strategy_rewards_applied=true where id=b.id;
  end if;
  return jsonb_build_object('applied',true,'isDraw',false,'stolenBudget',budget_take,'stolenInfluence',influence_take,
    'attackerLossPct',case when attacker_won then win_loss else lose_loss end,'defenderLossPct',case when attacker_won then lose_loss else win_loss end);
end;
$$;
revoke all on function public.gw_apply_battle_strategy_rewards(uuid) from public,anon,authenticated;
grant execute on function public.gw_apply_battle_strategy_rewards(uuid) to service_role;
