-- One active citizenship. State changes are only allowed between Beginner Island
-- and a normal state, once per 24h. Leaving Beginner Island applies the 72h
-- contribution penalty. Returning is restricted to low-level players/states and
-- recent presidents of strong states are excluded.
create or replace function public.gw_set_player_home_state(
  p_player_id uuid,
  p_state_id uuid,
  p_role text,
  p_membership_verified_at timestamptz default null
) returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  membership public.state_members%rowtype;
  player_row public.players%rowtype;
  current_state public.states%rowtype;
  target_state public.states%rowtype;
  previous_member public.state_members%rowtype;
  latest_previous_level integer;
  v_role text:=p_role;
  is_transition boolean:=false;
begin
  select * into player_row from public.players where id=p_player_id for update;
  if not found then raise exception 'Игрок не найден.'; end if;
  select * into target_state from public.states where id=p_state_id for update;
  if not found then raise exception 'Государство не найдено.'; end if;

  if v_role not in ('president','minister','deputy','general','citizen','member','curator') then raise exception 'Некорректная роль.'; end if;

  if player_row.home_state_id is not null and player_row.home_state_id<>p_state_id then
    select * into current_state from public.states where id=player_row.home_state_id for update;
    is_transition:=found;
  end if;

  if is_transition then
    -- Freeport is not a citizenship laundering route: once a player actually
    -- leaves one home state, the same 24h transition cooldown follows them.
    if player_row.last_state_change_at is not null and player_row.last_state_change_at>now()-interval '24 hours' then
      raise exception 'Менять государство можно не чаще одного раза в 24 часа.';
    end if;
    if not current_state.is_freeport and not target_state.is_freeport
      and not current_state.is_beginner_island and not target_state.is_beginner_island then
      raise exception 'Прямой переход между обычными государствами запрещён.';
    end if;

    select * into previous_member from public.state_members where state_id=current_state.id and player_id=p_player_id;

    if target_state.is_beginner_island then
      if current_state.is_freeport then
        select h.state_level into latest_previous_level
        from public.state_membership_history h
        where h.player_id=p_player_id
        order by h.left_at desc limit 1;
        if coalesce(latest_previous_level,1)>3 then
          raise exception 'Вернуться на Остров новичков можно только после государства не выше 3 уровня.';
        end if;
      elsif current_state.game_level>3 then
        raise exception 'Вернуться на Остров новичков можно только из государства не выше 3 уровня.';
      end if;
      if exists(
        select 1 from public.state_membership_history h
        where h.player_id=p_player_id and h.role='president' and h.state_level>3 and h.left_at>now()-interval '7 days'
      ) or (not current_state.is_freeport and previous_member.role='president' and current_state.game_level>3) then
        raise exception 'После управления сильным государством Остров новичков недоступен 7 дней.';
      end if;
    end if;

    if not current_state.is_freeport and previous_member.id is not null then
      insert into public.state_membership_history(player_id,state_id,role,state_level,joined_at,left_at)
      values(p_player_id,current_state.id,previous_member.role,greatest(1,current_state.game_level),previous_member.joined_at,now());
    end if;

    update public.players set
      last_state_change_at=now(),
      contribution_penalty_until=case when current_state.is_beginner_island then now()+interval '72 hours' else contribution_penalty_until end
    where id=p_player_id;
  end if;

  if target_state.is_beginner_island then
    v_role:=case when v_role='curator' then 'curator' else 'citizen' end;
    update public.states set owner_player_id=null,max_level=5 where id=target_state.id;
  elsif v_role='curator' then
    v_role:='citizen';
  end if;

  delete from public.state_members where player_id=p_player_id and state_id<>p_state_id;
  insert into public.state_members(state_id,player_id,role,membership_verified_at)
  values(p_state_id,p_player_id,v_role,p_membership_verified_at)
  on conflict(state_id,player_id) do update set role=excluded.role,membership_verified_at=excluded.membership_verified_at
  returning * into membership;
  update public.players set home_state_id=p_state_id where id=p_player_id;
  return membership.id;
end;
$$;
revoke all on function public.gw_set_player_home_state(uuid,uuid,text,timestamptz) from public,anon,authenticated;
grant execute on function public.gw_set_player_home_state(uuid,uuid,text,timestamptz) to service_role;

-- Rebuild the strategic aggregate with the defensive outpost and trade chamber.
create or replace function public.gw_refresh_state_strategy(p_state_id uuid)
returns public.states
language plpgsql
security definer
set search_path=public
as $$
declare
  s public.states%rowtype;
  active_count integer := 1;
  hq_level integer := 1;
  barracks_level integer := 1;
  lab_level integer := 1;
  outpost_level integer := 1;
  trade_level integer := 1;
  computed_level integer := 1;
  computed_size numeric := 1;
begin
  select * into s from public.states where id=p_state_id for update;
  if not found then raise exception 'Государство не найдено.'; end if;

  select greatest(1,count(*))::integer into active_count
  from public.state_members sm
  join public.players p on p.id=sm.player_id
  where sm.state_id=p_state_id and p.last_seen_at>=now()-interval '7 days';

  select coalesce(max(level),1) into hq_level from public.buildings where state_id=p_state_id and building_type='hq';
  select coalesce(max(level),1) into barracks_level from public.buildings where state_id=p_state_id and building_type='barracks';
  select coalesce(max(level),1) into lab_level from public.buildings where state_id=p_state_id and building_type='lab';
  select coalesce(max(level),1) into outpost_level from public.buildings where state_id=p_state_id and building_type='outpost';
  select coalesce(max(level),1) into trade_level from public.buildings where state_id=p_state_id and building_type='trade_chamber';

  computed_level:=least(s.max_level,greatest(1,hq_level+floor((barracks_level+lab_level+outpost_level+trade_level)/8.0)::integer));
  computed_size:=power(active_count::numeric,0.4)*power(greatest(1,computed_level)::numeric,0.6);
  update public.states set
    active_player_count=active_count,
    state_size=greatest(0.0001,computed_size),
    game_level=computed_level,
    army_power=greatest(100,100+barracks_level*55+lab_level*10+floor(rating/30.0)::integer),
    defense_power=greatest(100,100+hq_level*45+outpost_level*52+lab_level*12+floor(island_integrity*1.5)::integer),
    defense_buffer_base=least(0.20,0.06+outpost_level*0.012),
    last_size_refresh_at=now()
  where id=p_state_id
  returning * into s;
  return s;
end;
$$;
revoke all on function public.gw_refresh_state_strategy(uuid) from public,anon,authenticated;
grant execute on function public.gw_refresh_state_strategy(uuid) to service_role;

-- Complete timed upgrades idempotently. The project keeps PostgreSQL as the
-- authority, so a serverless instance does not need an in-memory timer.
create or replace function public.gw_finish_building_upgrades(p_state_id uuid)
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare
  completed integer:=0;
begin
  update public.buildings
  set level=greatest(level,coalesce(upgrade_target_level,level)),
      upgrade_started_at=null,
      upgrade_finishes_at=null,
      upgrade_target_level=null,
      upgrade_cooldown_until=now()+interval '5 minutes',
      updated_at=now()
  where state_id=p_state_id
    and upgrade_target_level is not null
    and upgrade_finishes_at is not null
    and upgrade_finishes_at<=now();
  get diagnostics completed = row_count;
  return completed;
end;
$$;
