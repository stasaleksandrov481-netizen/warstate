/**
 * WARSTATE v5 copy boundary.
 *
 * The database intentionally keeps legacy island-oriented identifiers for
 * backwards compatibility. Historical PostgreSQL functions can therefore
 * still return old wording until every environment has all migrations. Never
 * leak that terminology into the v5 UI or bot responses.
 */
export function normalizeWarstateCopy(value: unknown): string {
  let text = String(value || "").trim();
  if (!text) return text;

  const replacements: Array<[RegExp, string]> = [
    [/Freeport/g, "Нейтральная зона"],
    [/Острове новичков/g, "учебном округе"],
    [/острове новичков/g, "учебном округе"],
    [/Острова новичков/g, "учебного округа"],
    [/острова новичков/g, "учебного округа"],
    [/Остров новичков/g, "Учебный округ"],
    [/остров новичков/g, "учебный округ"],
    [/островной битвы/g, "битвы"],
    [/Островной битвы/g, "Битвы"],
    [/собственный остров/g, "собственное государство"],
    [/Собственный остров/g, "Собственное государство"],
    [/Ваш остров в руинах/g, "Ваше государство восстанавливается"],
    [/ваш остров в руинах/g, "ваше государство восстанавливается"],
    [/Этот остров уже разрушен/g, "Это государство уже выведено из строя"],
    [/этот остров уже разрушен/g, "это государство уже выведено из строя"],
    [/Остров находится под защитой/g, "Государство находится под защитой"],
    [/остров находится под защитой/g, "государство находится под защитой"],
    [/морской операции/g, "военной операции"],
    [/Морской операции/g, "Военной операции"],
    [/Один из островов/g, "Одно из государств"],
    [/один из островов/g, "одно из государств"],
    [/союзный остров/g, "союзное государство"],
    [/Союзный остров/g, "Союзное государство"],
    [/Между островами/g, "Между государствами"],
    [/между островами/g, "между государствами"],
    [/Остров не найден/g, "Государство не найдено"],
    [/остров не найден/g, "государство не найдено"],
  ];

  for (const [pattern, replacement] of replacements) text = text.replace(pattern, replacement);
  return text;
}
