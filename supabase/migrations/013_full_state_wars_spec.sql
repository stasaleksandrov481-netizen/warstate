-- Apply the strategic post-battle layer exactly once. Existing v1.4 island
-- integrity/ELO resolution stays intact; this adds limited resource capture,
-- influence loss, loss percentages and recovery protection.
create or replace function public.gw_apply_battle_strategy_rewards(p_battle_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  b public.battles%rowtype;
  a public.states%rowtype;
  d public.states%rowtype;
  attacker_won boolean;
  score_total numeric := 1;
  margin numeric := 0;
  win_loss numeric := 0.10;
  lose_loss numeric := 0.18;
  budget_pct numeric := 0.20;
  influence_pct numeric := 0.15;
  budget_cap bigint := 0;
  budget_take bigint := 0;
  influence_take bigint := 0;
begin
  select * into b from public.battles where id=p_battle_id for update;
  if not found then raise exception 'Битва не найдена.'; end if;
  if b.status <> 'resolved' then raise exception 'Битва ещё не завершена.'; end if;
  if b.strategy_rewards_applied then
    return jsonb_build_object('applied',false,'stolenBudget',b.stolen_budget,'stolenInfluence',b.stolen_influence,'attackerLossPct',b.attacker_loss_pct,'defenderLossPct',b.defender_loss_pct);
  end if;
  if b.defender_state_id is null then
    update public.battles set strategy_rewards_applied=true where id=b.id;
    return jsonb_build_object('applied',true);
  end if;

  perform 1 from public.states where id in (b.attacker_state_id,b.defender_state_id) order by id for update;
  select * into a from public.states where id=b.attacker_state_id;
  select * into d from public.states where id=b.defender_state_id;
  attacker_won := b.winner_state_id=b.attacker_state_id;
  score_total := greatest(1,b.attacker_score+b.defender_score);
  margin := abs(b.attacker_score-b.defender_score)/score_total;
  win_loss := least(0.18,greatest(0.05,0.08+margin*0.12));
  lose_loss := least(0.25,greatest(0.15,0.16+margin*0.16));

  if b.battle_type='siege' then budget_pct:=0.12; influence_pct:=0.10;
  elsif b.battle_type='territory' then budget_pct:=0.08; influence_pct:=0.08;
  end if;

  if attacker_won then
    -- A destroyed island already loses credits in gw_finalize_battle; do not
    -- double-charge it. Influence can still be captured.
    budget_cap := least(5000::bigint,(1000 + a.game_level*300)::bigint);
    if d.destroyed_until is null or d.destroyed_until <= now() then
      budget_take := least(floor(d.credits*budget_pct)::bigint,budget_cap);
    end if;
    influence_take := least(floor(d.influence*influence_pct)::bigint,greatest(50::bigint,budget_cap/10));

    update public.states set
      credits=greatest(0,credits-budget_take),
      influence=greatest(0,influence-influence_take),
      shield_until=greatest(coalesce(shield_until,now()),now()+interval '8 hours')
    where id=d.id;
    update public.states set credits=credits+budget_take,influence=influence+influence_take where id=a.id;

    update public.battles set
      attacker_loss_pct=round(win_loss,4),
      defender_loss_pct=round(lose_loss,4),
      stolen_budget=budget_take,
      stolen_influence=influence_take,
      strategy_rewards_applied=true
    where id=b.id;
  else
    update public.states set shield_until=greatest(coalesce(shield_until,now()),now()+interval '6 hours') where id=a.id;
    update public.battles set
      attacker_loss_pct=round(lose_loss,4),
      defender_loss_pct=round(win_loss,4),
      stolen_budget=0,
      stolen_influence=0,
      strategy_rewards_applied=true
    where id=b.id;
  end if;

  return jsonb_build_object(
    'applied',true,
    'stolenBudget',budget_take,
    'stolenInfluence',influence_take,
    'attackerLossPct',case when attacker_won then win_loss else lose_loss end,
    'defenderLossPct',case when attacker_won then lose_loss else win_loss end
  );
end;
$$;
revoke all on function public.gw_apply_battle_strategy_rewards(uuid) from public,anon,authenticated;
grant execute on function public.gw_apply_battle_strategy_rewards(uuid) to service_role;

-- Include protected Beginner Island status and strategic metrics in the
-- procedural world payload. Rank is global among non-Freeport states; nearby
-- filtering must not reset it to zero.
drop function if exists public.gw_get_islands(double precision,double precision,double precision,integer);
create function public.gw_get_islands(
  p_center_x double precision,
  p_center_y double precision,
  p_radius double precision default 2600,
  p_limit integer default 120
) returns table(
  id uuid,name text,color text,emblem text,world_x double precision,world_y double precision,
  telegram_member_count integer,rating integer,island_wins integer,island_losses integer,
  island_integrity integer,win_streak integer,last_battle_at timestamptz,destroyed_until timestamptz,
  shield_until timestamptz,chat_avatar_file_id text,is_freeport boolean,is_beginner_island boolean,
  game_level integer,max_level integer,influence bigint,reputation integer,army_power integer,defense_power integer,
  active_player_count integer,state_size numeric,rank bigint
)
language sql stable security definer set search_path=public
as $$
  with ranked as (
    select
      s.id,s.name,s.color,coalesce(s.emblem,'◆') as emblem,s.world_x,s.world_y,
      greatest(1,coalesce(s.telegram_member_count,1)) as telegram_member_count,
      greatest(0,coalesce(s.rating,1000)) as rating,
      greatest(0,coalesce(s.island_wins,0)) as island_wins,
      greatest(0,coalesce(s.island_losses,0)) as island_losses,
      greatest(0,least(100,coalesce(s.island_integrity,100))) as island_integrity,
      greatest(0,coalesce(s.win_streak,0)) as win_streak,
      s.last_battle_at,s.destroyed_until,s.shield_until,s.chat_avatar_file_id,
      s.is_freeport,s.is_beginner_island,s.game_level,s.max_level,s.influence,s.reputation,
      s.army_power,s.defense_power,s.active_player_count,s.state_size,s.created_at,
      ((s.world_x-p_center_x)^2+(s.world_y-p_center_y)^2) as distance_sq,
      case when s.is_freeport then 0::bigint else (
        select (1+count(*))::bigint from public.states r
        where not coalesce(r.is_freeport,false) and (
          greatest(0,coalesce(r.rating,1000)) > greatest(0,coalesce(s.rating,1000))
          or (greatest(0,coalesce(r.rating,1000)) = greatest(0,coalesce(s.rating,1000)) and r.created_at < s.created_at)
        )
      ) end as world_rank
    from public.states s
  ), nearby as (
    select * from ranked r
    where r.world_x between p_center_x-greatest(250.0,least(6500.0,p_radius)) and p_center_x+greatest(250.0,least(6500.0,p_radius))
      and r.world_y between p_center_y-greatest(250.0,least(6500.0,p_radius)) and p_center_y+greatest(250.0,least(6500.0,p_radius))
      and r.distance_sq<=power(greatest(250.0,least(6500.0,p_radius)),2)
    order by r.distance_sq asc limit least(greatest(p_limit,1),180)
  )
  select n.id,n.name,n.color,n.emblem,n.world_x,n.world_y,n.telegram_member_count,n.rating,n.island_wins,n.island_losses,
    n.island_integrity,n.win_streak,n.last_battle_at,n.destroyed_until,n.shield_until,n.chat_avatar_file_id,n.is_freeport,n.is_beginner_island,
    n.game_level,n.max_level,n.influence,n.reputation,n.army_power,n.defense_power,n.active_player_count,n.state_size,n.world_rank
  from nearby n order by n.distance_sq asc;
$$;
revoke all on function public.gw_get_islands(double precision,double precision,double precision,integer) from public,anon,authenticated;
