-- Refresh cached state-size and strategic power from real activity and buildings.
create or replace function public.gw_refresh_state_strategy(p_state_id uuid)
returns public.states
language plpgsql
security definer
set search_path=public
as $$
declare
  s public.states%rowtype;
  active_count integer := 1;
  hq_level integer := 1;
  barracks_level integer := 1;
  lab_level integer := 1;
  computed_size numeric := 1;
begin
  select * into s from public.states where id=p_state_id for update;
  if not found then raise exception 'Государство не найдено.'; end if;

  select greatest(1,count(*))::integer into active_count
  from public.state_members sm
  join public.players p on p.id=sm.player_id
  where sm.state_id=p_state_id and p.last_seen_at >= now()-interval '7 days';

  select coalesce(max(level),1) into hq_level from public.buildings where state_id=p_state_id and building_type='hq';
  select coalesce(max(level),1) into barracks_level from public.buildings where state_id=p_state_id and building_type='barracks';
  select coalesce(max(level),1) into lab_level from public.buildings where state_id=p_state_id and building_type='lab';

  computed_size := power(active_count::numeric,0.4) * power(greatest(1,hq_level)::numeric,0.6);
  update public.states set
    active_player_count=active_count,
    state_size=greatest(0.0001,computed_size),
    game_level=least(max_level,greatest(1,hq_level + floor((barracks_level+lab_level)/4.0)::integer)),
    army_power=greatest(100,100 + barracks_level*55 + lab_level*10 + floor(rating/30.0)::integer),
    defense_power=greatest(100,100 + hq_level*45 + lab_level*12 + floor(island_integrity*1.5)::integer),
    last_size_refresh_at=now()
  where id=p_state_id
  returning * into s;
  return s;
end;
$$;
revoke all on function public.gw_refresh_state_strategy(uuid) from public,anon,authenticated;
grant execute on function public.gw_refresh_state_strategy(uuid) to service_role;

-- Activity resolution is authoritative and idempotency is enforced by the daily
-- count. Every player may resolve at most four choice activities per UTC day.
create or replace function public.gw_complete_activity(
  p_player_id uuid,
  p_state_id uuid,
  p_activity_key text,
  p_option_key text
) returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  tpl public.activity_templates%rowtype;
  s public.states%rowtype;
  option_data jsonb;
  risk numeric := 0;
  success boolean := true;
  rc integer := 0;
  ri integer := 0;
  rt integer := 0;
  rr integer := 0;
  rcon integer := 0;
  result_message text;
  run_id uuid;
begin
  perform 1 from public.players where id=p_player_id for update;
  if not found then raise exception 'Игрок не найден.'; end if;
  select * into s from public.states where id=p_state_id for update;
  if not found then raise exception 'Государство не найдено.'; end if;
  if not exists(select 1 from public.state_members where player_id=p_player_id and state_id=p_state_id) then
    raise exception 'Игрок не состоит в этом государстве.';
  end if;
  if (select count(*) from public.player_activity_runs where player_id=p_player_id and completed_at>=date_trunc('day',now())) >= 4 then
    raise exception 'Сегодня уже выполнено четыре активности.';
  end if;
  if exists(select 1 from public.player_activity_runs where player_id=p_player_id and activity_key=p_activity_key and completed_at>=date_trunc('day',now())) then
    raise exception 'Эта активность уже выполнена сегодня.';
  end if;

  select * into tpl from public.activity_templates where key=p_activity_key and active=true;
  if not found then raise exception 'Активность не найдена.'; end if;
  if s.is_beginner_island and not tpl.beginner_allowed then raise exception 'Эта активность пока недоступна на Острове новичков.'; end if;

  select value into option_data from jsonb_array_elements(tpl.options) where value->>'key'=p_option_key limit 1;
  if option_data is null then raise exception 'Вариант действия не найден.'; end if;

  risk := greatest(0,least(0.8,coalesce((option_data->>'risk')::numeric,0)));
  -- Beginner Island guarantees a safer minimum-success experience.
  if s.is_beginner_island then risk := least(risk,0.08); end if;
  success := random() >= risk;
  rc := coalesce((option_data->>'credits')::integer,0);
  ri := coalesce((option_data->>'influence')::integer,0);
  rt := coalesce((option_data->>'tech')::integer,0);
  rr := coalesce((option_data->>'reputation')::integer,0);
  rcon := coalesce((option_data->>'contribution')::integer,0);

  if not success then
    rc := floor(rc*0.25)::integer; ri := floor(ri*0.25)::integer; rt := floor(rt*0.25)::integer;
    rr := least(rr,-2); rcon := greatest(2,floor(rcon*0.4)::integer);
    result_message := 'План сработал не полностью. Часть награды потеряна из-за риска.';
  else
    result_message := 'Операция выполнена успешно.';
  end if;

  update public.states set credits=credits+greatest(0,rc), influence=influence+greatest(0,ri), tech=tech+greatest(0,rt), reputation=greatest(-1000,least(1000,reputation+rr)) where id=p_state_id;
  update public.state_members set contribution=greatest(0,contribution+rcon) where state_id=p_state_id and player_id=p_player_id;
  update public.players set xp=xp+greatest(2,rcon), personal_reputation=personal_reputation+rr where id=p_player_id;
  insert into public.contribution_events(player_id,state_id,source,amount,metadata) values(p_player_id,p_state_id,'activity',rcon,jsonb_build_object('activity',p_activity_key,'option',p_option_key,'success',success));
  insert into public.player_activity_runs(player_id,state_id,activity_key,option_key,result_text,reward_credits,reward_influence,reward_tech,reward_reputation,reward_contribution)
    values(p_player_id,p_state_id,p_activity_key,p_option_key,result_message,rc,ri,rt,rr,rcon) returning id into run_id;

  return jsonb_build_object('id',run_id,'success',success,'text',result_message,'credits',rc,'influence',ri,'tech',rt,'reputation',rr,'contribution',rcon);
end;
$$;
revoke all on function public.gw_complete_activity(uuid,uuid,text,text) from public,anon,authenticated;
grant execute on function public.gw_complete_activity(uuid,uuid,text,text) to service_role;

-- Strategic battle metadata is generated at the DB boundary so attacks started
-- from Telegram and Mini App cannot diverge.
create or replace function public.gw_prepare_battle_strategy()
returns trigger
language plpgsql
set search_path=public
as $$
declare
  a public.states%rowtype;
  d public.states%rowtype;
  ratio numeric := 1;
  size_log numeric := 0;
  recent_attacks integer := 0;
  aggr numeric := 0;
  rep_bonus numeric := 0;
  seed bigint;
begin
  if new.battle_kind <> 'island' or new.defender_state_id is null then return new; end if;
  select * into a from public.gw_refresh_state_strategy(new.attacker_state_id);
  select * into d from public.gw_refresh_state_strategy(new.defender_state_id);

  if a.is_beginner_island then raise exception 'Атаки с Острова новичков запрещены.'; end if;
  if d.is_beginner_island then raise exception 'Остров новичков находится под защитой.'; end if;

  ratio := greatest(0.0001,a.state_size/greatest(0.0001,d.state_size));
  size_log := greatest(0,ln(ratio)/ln(2.0));
  select count(*)::integer into recent_attacks from public.battles where attacker_state_id=a.id and created_at>=now()-interval '7 days';
  aggr := case when recent_attacks>=3 then least(0.15,(recent_attacks-2)*0.05) else 0 end;
  rep_bonus := greatest(0,least(0.12,d.reputation/5000.0));
  seed := floor(random()*900000000000000000)::bigint + 1000000;

  new.attacker_state_size := a.state_size;
  new.defender_state_size := d.state_size;
  new.attacker_size_modifier := round(1-least(0.30,0.08*size_log),4);
  new.defender_size_modifier := round(1+least(0.25,0.07*size_log),4);
  new.underdog_bonus := round(least(0.25,0.07*size_log),4);
  new.aggression_penalty := round(aggr,4);
  new.defense_buffer_pct := round(least(0.20,d.defense_buffer_base+rep_bonus),4);
  new.attacker_raw_power := a.army_power;
  new.defender_raw_power := d.defense_power;
  new.random_seed := seed;
  new.attacker_random_modifier := round((0.85+random()*0.30)::numeric,4);
  new.defender_random_modifier := round((0.85+random()*0.30)::numeric,4);
  new.attacker_final_power := greatest(1,round(a.army_power*new.attacker_size_modifier*(1-new.aggression_penalty)*new.attacker_random_modifier));
  new.defender_final_power := greatest(1,round((d.defense_power*new.defender_size_modifier*(1+new.defense_buffer_pct))*new.defender_random_modifier));
  return new;
end;
$$;

drop trigger if exists trg_gw_prepare_battle_strategy on public.battles;
create trigger trg_gw_prepare_battle_strategy before insert on public.battles for each row execute function public.gw_prepare_battle_strategy();

-- Voluntary alliance support. One supporting state per battle, capped so allies
-- help but cannot replace the fighting state's own army.
create or replace function public.gw_add_battle_support(
  p_battle_id uuid,
  p_support_state_id uuid,
  p_player_id uuid,
  p_side text
) returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  b public.battles%rowtype;
  support_state public.states%rowtype;
  base_power integer;
  current_support integer := 0;
  cap_power integer;
  granted integer;
  target_state uuid;
begin
  if p_side not in ('attacker','defender') then raise exception 'Некорректная сторона поддержки.'; end if;
  select * into b from public.battles where id=p_battle_id for update;
  if not found or b.status not in ('scheduled','active') then raise exception 'Битва уже недоступна для поддержки.'; end if;
  if not exists(select 1 from public.state_members where state_id=p_support_state_id and player_id=p_player_id and role in ('president','minister','general')) then
    raise exception 'Поддержку может отправить руководство государства.';
  end if;
  if p_support_state_id in (b.attacker_state_id,b.defender_state_id) then raise exception 'Участник боя не считается союзной поддержкой.'; end if;
  select * into support_state from public.gw_refresh_state_strategy(p_support_state_id);
  if support_state.is_beginner_island and p_side='attacker' then raise exception 'Остров новичков может помогать только в обороне.'; end if;

  target_state := case when p_side='attacker' then b.attacker_state_id else b.defender_state_id end;
  if not exists (
    select 1 from public.diplomacy_relations dr
    where ((dr.state_a_id=p_support_state_id and dr.state_b_id=target_state) or (dr.state_b_id=p_support_state_id and dr.state_a_id=target_state))
      and dr.status='allied'
  ) then raise exception 'Поддерживать можно только союзника.'; end if;

  base_power := case when p_side='attacker' then b.attacker_raw_power else b.defender_raw_power end;
  cap_power := greatest(1,floor(base_power*0.35)::integer);
  select coalesce(sum(power_given),0)::integer into current_support from public.battle_supports where battle_id=p_battle_id and side=p_side;
  granted := least(greatest(1,floor((case when p_side='attacker' then support_state.army_power else support_state.defense_power end)*0.15)::integer),greatest(0,cap_power-current_support));
  if granted<=0 then raise exception 'Лимит союзной поддержки для этой стороны уже достигнут.'; end if;

  insert into public.battle_supports(battle_id,state_id,side,support_type,power_given,contributed_by_player_id)
    values(p_battle_id,p_support_state_id,p_side,case when p_side='attacker' then 'attack' else 'defense' end,granted,p_player_id);
  insert into public.contribution_events(player_id,state_id,source,amount,metadata) values(p_player_id,p_support_state_id,'support',greatest(5,granted/20),jsonb_build_object('battleId',p_battle_id,'side',p_side));
  update public.state_members set contribution=contribution+greatest(5,granted/20) where player_id=p_player_id and state_id=p_support_state_id;
  return jsonb_build_object('power',granted,'side',p_side,'cap',cap_power);
end;
$$;
revoke all on function public.gw_add_battle_support(uuid,uuid,uuid,text) from public,anon,authenticated;
grant execute on function public.gw_add_battle_support(uuid,uuid,uuid,text) to service_role;

